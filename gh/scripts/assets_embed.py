#!/usr/bin/env python3
"""
Dual Citizen asset embedder.

Generates uAssetsEmbedded.pas: every on-disk asset file under
assets/{common,facebook,reddit} is stored as a base64-encoded string constant
keyed by its relative path, plus HasEmbeddedAsset/EmbeddedAsset functions.
The Pascal asset loader prefers embedded content and falls back to reading
the file from ASSETS_ROOT, so a single binary can ship without loose asset
files.

Usage:
  assets_embed.py [out_pas_unit]
"""

import base64
import sys
from pathlib import Path

ASSETS = Path('/home/lilareyon/dual-citizen/assets')


def collect_files():
    files = []
    common = ASSETS / 'common'
    if common.exists():
        for f in sorted(common.iterdir()):
            if f.is_file():
                files.append(f.relative_to(ASSETS).as_posix())
    for site in ('facebook', 'reddit'):
        sdir = ASSETS / site
        if not sdir.exists():
            continue
        for f in sorted(sdir.rglob('*')):
            if f.is_file():
                files.append(f.relative_to(ASSETS).as_posix())
    return sorted(set(files))


def pascal_str(s, max_line=80):
    """Convert string to Pascal string literal, splitting long strings into adjacent literals with + concatenation."""
    out = []
    for i in range(0, len(s), max_line):
        chunk = s[i:i+max_line]
        # Escape for Pascal string
        escaped = ''
        for ch in chunk:
            if ch == "'":
                escaped += "''"
            elif ch == '\\':
                escaped += '\\\\'
            elif ch == '\n':
                escaped += '#10'
            elif ch == '\r':
                escaped += '#13'
            elif ch == '\t':
                escaped += '#9'
            elif ord(ch) < 32 or ord(ch) == 127:
                escaped += '#%d' % ord(ch)
            else:
                escaped += ch
        out.append("'" + escaped + "'")
    return out


def ident_for(rel):
    return 'DCASSET_' + rel.replace('/', '_').replace('.', '_').replace('-', '_')


def build_unit(files):
    lines = []
    lines.append('unit uAssetsEmbedded;')
    lines.append('')
    lines.append('{ =========================================================================')
    lines.append('  uAssetsEmbedded — on-disk asset system, embedded payloads')
    lines.append('')
    lines.append('  Auto-generated by assets_embed.py. DO NOT EDIT BY HAND.')
    lines.append('  Every asset under assets/common,facebook,reddit is stored here as a')
    lines.append('  base64 string keyed by its path relative to ASSETS_ROOT. The Pascal')
    lines.append('  asset loader (uControllerBrowser) prefers embedded content when')
    lines.append('  available and falls back to reading the file from ASSETS_ROOT, so this')
    lines.append('  unit makes a single-binary deploy possible without shipping loose')
    lines.append('  asset files.')
    lines.append('  ========================================================================= }')
    lines.append('')
    lines.append('{$mode objfpc}{$H+}')
    lines.append('')
    lines.append('interface')
    lines.append('')
    lines.append('uses SysUtils, fpjson;')
    lines.append('')
    lines.append('function HasEmbeddedAsset(const RelPath: string): Boolean;')
    lines.append('function EmbeddedAsset(const RelPath: string; out Content: string): Boolean;')
    lines.append('')
    lines.append('implementation')
    lines.append('')
    lines.append('uses Base64, Classes;')
    lines.append('')
    lines.append('const')
    for i, rel in enumerate(files):
        data = (ASSETS / rel).read_bytes()
        b64 = base64.b64encode(data).decode('ascii')
        ident = ident_for(rel)
        pascal_chunks = pascal_str(b64)
        if len(pascal_chunks) == 1:
            lines.append('  %s = %s;  // %s (%d bytes)' % (ident, pascal_chunks[0], rel, len(data)))
        else:
            lines.append('  %s =' % ident)
            for j, chunk in enumerate(pascal_chunks):
                if j == 0:
                    line = '    ' + chunk + ' +'
                elif j == len(pascal_chunks) - 1:
                    line = '    ' + chunk + ';  // %s (%d bytes)' % (rel, len(data))
                else:
                    line = '    ' + chunk + ' +'
                lines.append(line)
    lines.append('')
    lines.append('var')
    lines.append('  FEmbeddedPaths: TStringList = nil;')
    lines.append('  FEmbeddedB64: TStringList = nil;')
    lines.append('')
    lines.append('function EmbeddedAssetCache: TStringList;')
    lines.append('begin')
    lines.append('  if FEmbeddedPaths = nil then')
    lines.append('  begin')
    lines.append('    FEmbeddedPaths := TStringList.Create;')
    lines.append('    FEmbeddedPaths.Sorted := True;')
    lines.append('    FEmbeddedPaths.Duplicates := dupIgnore;')
    lines.append('    FEmbeddedB64 := TStringList.Create;')
    lines.append('  end;')
    lines.append('  Result := FEmbeddedPaths;')
    lines.append('end;')
    lines.append('')
    lines.append('function HasEmbeddedAsset(const RelPath: string): Boolean;')
    lines.append('begin')
    lines.append('  Result := EmbeddedAssetCache.IndexOf(RelPath) >= 0;')
    lines.append('end;')
    lines.append('')
    lines.append('function EmbeddedAsset(const RelPath: string; out Content: string): Boolean;')
    lines.append('var')
    lines.append('  idx: Integer;')
    lines.append('  b64: string;')
    lines.append('begin')
    lines.append('  Result := False;')
    lines.append("  Content := '';")
    lines.append('  idx := EmbeddedAssetCache.IndexOf(RelPath);')
    lines.append('  if idx < 0 then Exit;')
    lines.append('  b64 := FEmbeddedB64[idx];')
    lines.append('  Content := DecodeStringBase64(b64);')
    lines.append('  Result := True;')
    lines.append('end;')
    lines.append('')
    lines.append('initialization')
    lines.append('  FEmbeddedPaths := TStringList.Create;')
    lines.append('  FEmbeddedPaths.Sorted := True;')
    lines.append('  FEmbeddedPaths.Duplicates := dupIgnore;')
    lines.append('  FEmbeddedB64 := TStringList.Create;')
    for rel in files:
        lines.append('  FEmbeddedPaths.Add(%s);' % pascal_str(rel)[0])
        lines.append('  FEmbeddedB64.Add(%s);' % ident_for(rel))
    lines.append('')
    lines.append('finalization')
    lines.append('  FEmbeddedPaths.Free;')
    lines.append('  FEmbeddedB64.Free;')
    lines.append('end.')
    lines.append('')
    return '\n'.join(lines)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'uAssetsEmbedded.pas'
    files = collect_files()
    Path(out).write_text(build_unit(files) + '\n')
    print('Embedded %d assets into %s' % (len(files), out))


if __name__ == '__main__':
    main()